func TestVarcharToTextMigrationContract(t *testing.T) {
	up, down := readMigrationSections(t, varcharToTextMigration)

	if got, want := strings.Count(up, "TYPE text"), len(varcharToTextColumns); got != want {
		t.Fatalf("up converts %d columns, contract lists %d: update this test alongside the migration", got, want)
	}
	if got, want := strings.Count(down, "TYPE character varying("), len(varcharToTextColumns); got != want {
		t.Fatalf("down restores %d columns, contract lists %d", got, want)
	}

	for _, c := range varcharToTextColumns {
		alter := fmt.Sprintf("ALTER COLUMN %s TYPE text", c.column)
		// The ALTER TABLE for this column's table must precede the ALTER
		// COLUMN, and no other table's ALTER may sit between them.
		if !columnAlteredOn(up, c.table, alter) {
			t.Errorf("up missing %q on public.%s", alter, c.table)
		}
		restore := fmt.Sprintf("ALTER COLUMN %s TYPE character varying(%d)", c.column, c.length)
		if !columnAlteredOn(down, c.table, restore) {
			t.Errorf("down missing %q on public.%s", restore, c.table)
		}
	}

	// A USING clause or a CHECK would turn a catalog-only change into a
	// rewrite or a new rule; neither belongs here.
	for _, forbidden := range []string{" USING ", "ADD CONSTRAINT", "CHECK ("} {
		if strings.Contains(up, forbidden) {
			t.Errorf("up must stay a metadata-only ALTER TYPE; found %q", forbidden)
		}
	}

	// device_name's DEFAULT is the one literal that has to follow the type.
	if !strings.Contains(up, "ALTER COLUMN device_name SET DEFAULT ''::text") {
		t.Error("up must re-express web_push_subscriptions.device_name's default as text")
	}
	if !strings.Contains(down, "ALTER COLUMN device_name SET DEFAULT ''::character varying") {
		t.Error("down must restore web_push_subscriptions.device_name's varchar default")
	}
}

// columnAlteredOn reports whether alter appears inside an ALTER TABLE
// public.<table> statement in body.
func columnAlteredOn(body, table, alter string) bool {
	for _, stmt := range strings.Split(body, ";") {
		stmt = strings.TrimSpace(stmt)
		if strings.HasPrefix(stmt, "ALTER TABLE public."+table+" ") && strings.Contains(stmt, alter) {
			return true
		}
	}
	return false
}

