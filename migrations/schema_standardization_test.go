func TestRenameTablesMigrationContract(t *testing.T) {
	up, down := readMigrationSections(t, renameTablesMigration)

	if got, want := strings.Count(up, "ALTER TABLE public.")-strings.Count(up, "RENAME CONSTRAINT"), len(renamePairs); got != want {
		t.Fatalf("up renames %d tables, contract lists %d: update this test alongside the migration", got, want)
	}

	for _, p := range renamePairs {
		upTable := fmt.Sprintf("ALTER TABLE public.%s RENAME TO %s;", p.from, p.to)
		if !strings.Contains(up, upTable) {
			t.Errorf("up missing %q", upTable)
		}
		downTable := fmt.Sprintf("ALTER TABLE public.%s RENAME TO %s;", p.to, p.from)
		if !strings.Contains(down, downTable) {
			t.Errorf("down missing %q", downTable)
		}
		for oldIdx, newIdx := range p.indexes {
			if want := fmt.Sprintf("ALTER INDEX public.%s RENAME TO %s;", oldIdx, newIdx); !strings.Contains(up, want) {
				t.Errorf("up missing %q", want)
			}
			if want := fmt.Sprintf("ALTER INDEX public.%s RENAME TO %s;", newIdx, oldIdx); !strings.Contains(down, want) {
				t.Errorf("down missing %q", want)
			}
		}
		for oldCon, newCon := range p.constraints {
			if want := fmt.Sprintf("ALTER TABLE public.%s RENAME CONSTRAINT %s TO %s;", p.to, oldCon, newCon); !strings.Contains(up, want) {
				t.Errorf("up missing %q", want)
			}
			if want := fmt.Sprintf("ALTER TABLE public.%s RENAME CONSTRAINT %s TO %s;", p.to, newCon, oldCon); !strings.Contains(down, want) {
				t.Errorf("down missing %q", want)
			}
		}
		// Postgres 18 materializes NOT NULL as named constraints that RENAME
		// TABLE leaves behind; both directions sweep them by prefix.
		for _, section := range []string{up, down} {
			if !strings.Contains(section, fmt.Sprintf("('%s', '%s')", p.from, p.to)) &&
				!strings.Contains(section, fmt.Sprintf("('%s', '%s')", p.to, p.from)) {
				t.Errorf("NOT NULL constraint sweep does not list the %s/%s pair", p.from, p.to)
			}
		}
	}
	if !strings.Contains(up, "contype = 'n'") || !strings.Contains(down, "contype = 'n'") {
		t.Error("both sections must sweep the NOT NULL (contype 'n') constraints")
	}

	// No data or shape change rides along with the rename.
	for _, forbidden := range []string{"CREATE TABLE", "DROP TABLE", "INSERT", "UPDATE ", "DELETE", "ADD COLUMN", "DROP COLUMN"} {
		if strings.Contains(up, forbidden) || strings.Contains(down, forbidden) {
			t.Errorf("rename migration must not contain %q", forbidden)
		}
	}
}
