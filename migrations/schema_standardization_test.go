// targetsArray extracts the quoted names inside the first ARRAY[...] literal
// after marker in s.
func targetsArray(t *testing.T, s, marker string) []string {
	t.Helper()
	_, rest, ok := strings.Cut(s, marker)
	if !ok {
		t.Fatalf("missing %q", marker)
	}
	_, rest, ok = strings.Cut(rest, "ARRAY[")
	if !ok {
		t.Fatal("missing targets ARRAY[")
	}
	body, _, ok := strings.Cut(rest, "]")
	if !ok {
		t.Fatal("targets array unterminated")
	}
	var names []string
	for _, part := range strings.Split(body, ",") {
		names = append(names, strings.Trim(strings.TrimSpace(part), "'"))
	}
	return names
}

func TestSerialToIdentityMigrationContract(t *testing.T) {
	up, down := readMigrationSections(t, serialToIdentityMigration)

	for _, section := range []struct {
		name string
		body string
	}{{"up", up}, {"down", down}} {
		got := targetsArray(t, section.body, "targets text[]")
		if len(got) != len(serialToIdentityTables) {
			t.Fatalf("%s converts %d tables, contract lists %d: update this test alongside the migration",
				section.name, len(got), len(serialToIdentityTables))
		}
		for i, want := range serialToIdentityTables {
			if got[i] != want {
				t.Errorf("%s targets[%d] = %q, want %q (list is sorted and pinned)", section.name, i, got[i], want)
			}
		}
	}

	// BY DEFAULT is serial parity: an INSERT may still supply the id. ALWAYS
	// would reject internal/api/handlers/policy_test.go's explicit-id insert
	// and any restore path that carries ids across databases.
	if !strings.Contains(up, "ADD GENERATED BY DEFAULT AS IDENTITY") {
		t.Error("up must add the identity column as GENERATED BY DEFAULT")
	}
	if strings.Contains(up, "GENERATED ALWAYS") {
		t.Error("up must not convert any serial column to GENERATED ALWAYS")
	}

	// Sequence continuity: the old sequence's position is read after the
	// default is dropped (so nothing else can advance it) and before it is
	// dropped, then applied to the new identity sequence with is_called intact.
	steps := []string{
		"ALTER COLUMN id DROP DEFAULT",
		"SELECT last_value, is_called FROM %s",
		"DROP SEQUENCE %s",
		"ADD GENERATED BY DEFAULT AS IDENTITY",
		"PERFORM setval(pg_get_serial_sequence('public.' || quote_ident(target), 'id'), last_val, called)",
	}
	last := -1
	for _, step := range steps {
		at := strings.Index(up, step)
		if at < 0 {
			t.Fatalf("up missing continuity step %q", step)
		}
		if at < last {
			t.Errorf("up continuity step %q is out of order", step)
		}
		last = at
	}

	// The Down mirrors it: read the identity sequence, drop the identity,
	// recreate a sequence of the column's own type, position it, re-point the
	// default at it.
	last = -1
	for _, step := range []string{
		"SELECT last_value, is_called FROM %s",
		"ALTER COLUMN id DROP IDENTITY",
		"CREATE SEQUENCE public.%I AS %s OWNED BY public.%I.id",
		"PERFORM setval(format('public.%I', seq_name)::regclass, last_val, called)",
		"ALTER COLUMN id SET DEFAULT nextval(%L)",
	} {
		at := strings.Index(down, step)
		if at < 0 {
			t.Fatalf("down missing continuity step %q", step)
		}
		if at < last {
			t.Errorf("down continuity step %q is out of order", step)
		}
		last = at
	}

	// Idempotence guards: a column already in the target state is skipped, and
	// a table that vanished is an error rather than silently ignored.
	for _, want := range []string{
		"IF identity_kind IS NULL THEN RAISE EXCEPTION",
		"IF identity_kind <> '' THEN CONTINUE;",
	} {
		if !strings.Contains(up, want) {
			t.Errorf("up missing guard %q", want)
		}
	}
	if !strings.Contains(down, "IF identity_kind = '' THEN CONTINUE;") {
		t.Error("down missing already-serial skip guard")
	}
}

