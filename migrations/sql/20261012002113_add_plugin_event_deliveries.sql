-- +goose Up
-- Outbox for plugin event_consumer.v1 deliveries. The API server that
-- produced an event inserts one row per subscribing installation; any API
-- server claims due rows, calls HandleEvent, and deletes the row on success
-- or after the last retry. A claim pushes next_attempt_at out by a lease, so
-- a row whose claimer died is claimed again once the lease runs out.
CREATE TABLE public.plugin_event_deliveries (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id               TEXT NOT NULL,
    event_name             TEXT NOT NULL,
    -- json, not jsonb: jsonb refuses a \u0000 escape, which a plugin's
    -- payload may carry.
    payload                JSON,
    plugin_installation_id BIGINT NOT NULL REFERENCES public.plugin_installations(id) ON DELETE CASCADE,
    capability_id          TEXT NOT NULL,
    attempts               INTEGER NOT NULL DEFAULT 0,
    next_attempt_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error             TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX plugin_event_deliveries_due_idx
    ON public.plugin_event_deliveries (next_attempt_at, id);

CREATE INDEX plugin_event_deliveries_installation_idx
    ON public.plugin_event_deliveries (plugin_installation_id);

-- +goose Down
DROP TABLE IF EXISTS public.plugin_event_deliveries;
