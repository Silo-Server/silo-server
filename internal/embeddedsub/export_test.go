// GoldenFixture is a hand-built Matroska file for the FFmpeg comparison
// tests in package embeddedsub_test, with the subtitle track to compare.
type GoldenFixture struct {
	Name string
	Data []byte
	// Track is the subtitle's TrackNumber; Ordinal its FFmpeg subtitle
	// stream ordinal (0:s:N); Codec FFmpeg's codec name.
	Track   uint64
	Ordinal int
	Codec   string
}

// Matroska Audio element IDs, for the PCM track that gives a fixture its
// start time.
const (
	idAudio             = 0xE1
	idSamplingFrequency = 0xB5
	idChannels          = 0x9F
	idBitDepth          = 0x6264
)

const pcmTrack = 1

// pcmTrackEntry is an 8 kHz mono 8-bit PCM track: data FFmpeg demuxes
// without decoding, whose first packet sets the file's start time.
var pcmTrackEntry = fixtureTrack{number: pcmTrack, uid: 0x1001, kind: matroska.TrackTypeAudio, codec: "A_PCM/INT/LIT",
	extra: [][]byte{el(idAudio, floatEl(idSamplingFrequency, 8000), uintEl(idChannels, 1), uintEl(idBitDepth, 8))}}

// pcmBlock is half a second of silence.
func pcmBlock(rel int16) fixtureBlock {
	return fixtureBlock{track: pcmTrack, rel: rel, simple: true, frames: [][]byte{bytes.Repeat([]byte{0x80}, 4000)}, cue: cueNone}
}

// pgsDisplaySet is one PGS display set. With an object it shows a w×h
// bitmap of random colors, which doesn't compress; without it clears the
// screen.
func pgsDisplaySet(r *rand.Rand, composition uint16, w, h int) []byte {
	seg := func(kind byte, payload []byte) []byte {
		return append([]byte{kind, byte(len(payload) >> 8), byte(len(payload))}, payload...)
	}
	objects := byte(0)
	if w > 0 {
		objects = 1
	}
	pcs := []byte{0x07, 0x80, 0x04, 0x38, 0x10, byte(composition >> 8), byte(composition), 0x80, 0x00, 0x00, objects}
	if objects == 0 {
		pcs[7] = 0x00
		return concat(seg(0x16, pcs), seg(0x17, []byte{1, 0, 0, 100, 0, 100, 0, 1, 0, 1}), seg(0x80, nil))
	}
	pcs = append(pcs, 0, 0, 0, 0, 0, 100, 0, 100)
	wds := []byte{1, 0, 0, 100, 0, 100, byte(w >> 8), byte(w), byte(h >> 8), byte(h)}
	pds := []byte{0, 0}
	for i := 1; i < 256; i++ {
		pds = append(pds, byte(i), byte(16+i%200), 128, 128, 255)
	}
	var rle []byte
	for range h {
		for range w {
			rle = append(rle, byte(1+r.IntN(255)))
		}
		rle = append(rle, 0, 0)
	}
	n := len(rle) + 4
	ods := append([]byte{0, 0, 0, 0xC0, byte(n >> 16), byte(n >> 8), byte(n), byte(w >> 8), byte(w), byte(h >> 8), byte(h)}, rle...)
	return concat(seg(0x16, pcs), seg(0x17, wds), seg(0x14, pds), seg(0x15, ods), seg(0x80, nil))
}

func concat(parts ...[]byte) []byte { return bytes.Join(parts, nil) }

