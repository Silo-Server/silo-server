// GoldenFixtures are the hand-built files FFmpeg's output from the source
// is compared on: layouts its own muxer doesn't write.
func GoldenFixtures(t testing.TB) []GoldenFixture {
	r := rand.New(rand.NewPCG(1, 2))
	audio := func(startMS int16) []fixtureBlock {
		var b []fixtureBlock
		for rel := startMS; rel < 10_000; rel += 500 {
			b = append(b, pcmBlock(rel))
		}
		return b
	}
	withAudio := func(startMS int16, subs ...fixtureBlock) []fixtureCluster {
		return []fixtureCluster{{ticks: 0, blocks: append(audio(startMS), subs...)}}
	}

	pgs := mkvFixture{
		tracks: []fixtureTrack{pcmTrackEntry, {number: 2, uid: 0x2002, codec: "S_HDMV/PGS", extra: [][]byte{encodingEl(1, matroska.CompressionZlib, nil)}}},
		clusters: withAudio(1200,
			fixtureBlock{track: 2, rel: 2000, frames: [][]byte{zlibBytes(t, pgsDisplaySet(r, 1, 100, 60))}, duration: -1},
			fixtureBlock{track: 2, rel: 3500, frames: [][]byte{zlibBytes(t, pgsDisplaySet(r, 2, 0, 0))}, duration: -1},
			fixtureBlock{track: 2, rel: 5000, frames: [][]byte{zlibBytes(t, pgsDisplaySet(r, 3, 40, 20))}, duration: -1},
			fixtureBlock{track: 2, rel: 7000, frames: [][]byte{zlibBytes(t, pgsDisplaySet(r, 4, 0, 0))}, duration: -1},
		),
	}
	laced := mkvFixture{
		tracks: []fixtureTrack{pcmTrackEntry, {number: 2, uid: 0x2002, codec: "S_TEXT/UTF8"}},
		clusters: withAudio(0,
			textBlock(2, 500, 1200, "Plain <i>line</i>"),
			fixtureBlock{track: 2, rel: 2000, lacing: 1, frames: [][]byte{[]byte("Xiph one"), []byte("Xiph two"), []byte("Xiph three")}, duration: 3000},
			fixtureBlock{track: 2, rel: 5500, lacing: 3, frames: [][]byte{[]byte("EBML a"), []byte("EBML bb"), []byte("EBML c")}, duration: 1000},
			fixtureBlock{track: 2, rel: 7000, lacing: 2, frames: [][]byte{[]byte("fixed1"), []byte("fixed2")}, duration: 999},
		),
	}
	stripped := mkvFixture{
		tracks: []fixtureTrack{pcmTrackEntry, {number: 2, uid: 0x2002, codec: "S_TEXT/UTF8",
			extra: [][]byte{encodingEl(1, matroska.CompressionHeaderStripping, []byte("Stripped: "))}}},
		clusters: withAudio(0,
			textBlock(2, 1000, 1500, "first"),
			textBlock(2, 4000, 2000, "second\nline"),
		),
	}
	scanned := mkvFixture{
		tracks: []fixtureTrack{pcmTrackEntry, {number: 2, uid: 0x2002, codec: "S_TEXT/UTF8"}},
		clusters: withAudio(0,
			fixtureBlock{track: 2, rel: 1000, frames: [][]byte{[]byte("found by scan")}, duration: 900, cue: cueWithoutPosition},
			fixtureBlock{track: 2, rel: 6000, frames: [][]byte{[]byte("again")}, duration: 400, cue: cueWithoutPosition},
		),
	}
	ass := mkvFixture{
		tracks: []fixtureTrack{pcmTrackEntry, {number: 2, uid: 0x2002, codec: "S_TEXT/ASS", private: zlibBytes(t, goldenASSHeader),
			extra: [][]byte{encodingEl(3, matroska.CompressionZlib, nil)}}},
		clusters: withAudio(0,
			fixtureBlock{track: 2, rel: 1000, frames: [][]byte{zlibBytes(t, []byte(`1,0,Default,,0,0,0,,{\i1}Hello{\i0} there`))}, duration: 2000},
			fixtureBlock{track: 2, rel: 1500, frames: [][]byte{zlibBytes(t, []byte(`0,1,Sign,,0,0,0,,{\an8\pos(640,40)}SIGN`))}, duration: 6000},
			fixtureBlock{track: 2, rel: 4000, frames: [][]byte{zlibBytes(t, []byte(`2,0,Default,,0,0,0,,Bye`))}, duration: 1000},
		),
	}
	return []GoldenFixture{
		{Name: "zlib PGS after a 1.2 s start", Data: pgs.build(), Track: 2, Codec: "hdmv_pgs_subtitle"},
		{Name: "laced SubRip", Data: laced.build(), Track: 2, Codec: "subrip"},
		{Name: "header-stripped SubRip", Data: stripped.build(), Track: 2, Codec: "subrip"},
		{Name: "SubRip cued without relative positions", Data: scanned.build(), Track: 2, Codec: "subrip"},
		{Name: "zlib ASS with a compressed header", Data: ass.build(), Track: 2, Codec: "ass"},
	}
}

// WebVTTFixtures are the same cues as a Matroska S_TEXT/WEBVTT track, which
// keeps a cue's settings and identifier in the block's addition, and as a
// WebM D_WEBVTT/SUBTITLES track, which FFmpeg reads and keeps them in the
// block. The Matroska track has a cue without text, which the WebM one
// can't carry.
func WebVTTFixtures() (matroskaFile, webmFile []byte) {
	cues := []struct {
		rel                    int16
		duration               int64
		identifier, settings   string
		text                   string
		addition, comment, raw bool
	}{
		{rel: 1000, duration: 2000, identifier: "hello", text: "Hello <b>world</b>.", addition: true},
		{rel: 3500, duration: 1500, text: "Two lines\nof text"},
		{rel: 5500, duration: 1000, settings: "line:10% align:start", text: "At the top", addition: true},
		{rel: 7000, duration: 1000, identifier: "noted", text: "After a note", addition: true, comment: true},
		{rel: 8000, duration: 500, raw: true},
		{rel: 9000, duration: 800, text: "Last"},
	}
	var mkv, webm []fixtureBlock
	for _, c := range cues {
		b := textBlock(2, c.rel, c.duration, c.text)
		if c.addition {
			b.addition = []byte(c.settings + "\n" + c.identifier + "\n")
			if c.comment {
				b.addition = append(b.addition, "NOTE a comment\n"...)
			}
		}
		mkv = append(mkv, b)
		if !c.raw {
			webm = append(webm, textBlock(2, c.rel, c.duration, c.identifier+"\n"+c.settings+"\n"+c.text))
		}
	}
	build := func(codec string, blocks []fixtureBlock) []byte {
		var cluster []fixtureBlock
		for rel := int16(0); rel < 10_000; rel += 500 {
			cluster = append(cluster, pcmBlock(rel))
		}
		return mkvFixture{
			tracks:   []fixtureTrack{pcmTrackEntry, {number: 2, uid: 0x2002, codec: codec, private: []byte("WEBVTT")}},
			clusters: []fixtureCluster{{ticks: 0, blocks: append(cluster, blocks...)}},
		}.build()
	}
	return build(matroska.CodecIDWebVTT, mkv), build(matroska.CodecIDWebMWebVTT, webm)
}
