// Restoring admin collections, and the collection metadata budget every
// item that writes a collection is charged to.

func (a *applier) applyCollection(ctx context.Context, tx pgx.Tx, id string) (applied, error) {
	item := ReportItem{Kind: KindCollection, Label: id}
	c := indexed(a.rs.Collections.Collections, a.rs.lookup().collections, id)
	if c == nil {
		return leftOut(item, ReasonNotInBackup, "The backup has no such collection."), nil
	}
	item.Label = c.Title
	libMap := a.libraryMap()
	plan, err := a.planner(tx).planCollection(ctx, *c, libMap, nil)
	if err != nil {
		return applied{}, err
	}
	if plan.item.Reason == ReasonLibraryNotRestorable {
		return leftOut(item, ReasonLibraryNotMapped, "Its library is not on this server."), nil
	}
	if !plan.item.Selectable {
		return leftOutFor(item, plan.item), nil
	}
	if unknown := plan.item.Collection.UnknownItems; unknown > 0 {
		item.Notes = append(item.Notes, fmt.Sprintf("%d of its items are not in this server's catalog and were left out.", unknown))
	}
	charge := collectionCharge{library: libMap[c.LibraryID], bytes: collectionCost(*c)}
	if over, ok := a.overCollectionBudget(item, charge); ok {
		return over, nil
	}
	result, err := a.writeCollection(ctx, tx, id, plan, *c, libMap, item)
	if result.item.Outcome == OutcomeRestored {
		result.metadata = charge
	}
	return result, err
}

// writeCollection creates the collection or restores it onto the one here.
func (a *applier) writeCollection(ctx context.Context, tx pgx.Tx, id string, plan collectionPlan, c CollectionEntry, libMap map[int]int, item ReportItem) (applied, error) {
	if plan.localID != "" {
		return a.restoreOntoCollection(ctx, tx, id, plan, c, libMap, item)
	}

	// A smart query or a sync source names libraries too; one that would
	// lose its whole scope is left out rather than widened to every library.
	query, queryOK := userdata.RemapQueryLibraries(c.QueryDefinition, mapIn(libMap))
	source, sourceOK := userdata.RemapQueryLibraries(c.SourceConfig, mapIn(libMap))
	if !queryOK || !sourceOK {
		return leftOut(item, ReasonLibraryNotMapped, "Its rules or source name only libraries that are not on this server."), nil
	}
	newID, err := freeCollectionID(ctx, tx, c.ID)
	if err != nil {
		return applied{}, err
	}
	// Uploaded artwork is copied under the new collection's keys before the
	// row that references it.
	poster, err := a.copyCollectionArt(ctx, c.ID, newID, c.Poster, &item)
	if err != nil {
		return applied{}, err
	}
	backdrop, err := a.copyCollectionArt(ctx, c.ID, newID, c.Backdrop, &item)
	if err != nil {
		return applied{}, err
	}
	primary := plan.scope[0]
	slug, err := freeSlug(ctx, tx, primary, c.Slug)
	if err != nil {
		return applied{}, err
	}
	if err := a.createCollection(ctx, tx, catalog.CreateLibraryCollectionInput{
		ID: newID, LibraryID: primary, LibraryIDs: plan.scope, Slug: slug, Title: c.Title, Description: c.Description,
		CollectionType: c.CollectionType, Visibility: c.Visibility, SortOrder: c.SortOrder, Featured: c.Featured,
		PosterURL: poster, BackdropURL: backdrop, PosterThumbhash: thumbFor(poster, c.PosterThumbhash), BackdropThumbhash: thumbFor(backdrop, c.BackdropThumbhash),
		PosterAutoGenerated: c.PosterAutoGenerated, SourceURL: c.SourceURL,
		QueryDefinition: query, SortConfig: c.SortConfig, SourceConfig: source,
		SyncSchedule: c.SyncSchedule,
	}, true, &item.Notes); err != nil {
		return applied{}, err
	}
	if _, err := catalog.AddMissingItemsInTx(ctx, tx, newID, plan.missing); err != nil {
		return applied{}, err
	}
	if _, err := restoreGroups(ctx, tx, newID, c, libMap); err != nil {
		return applied{}, err
	}
	a.claim(claimCollection, newID, id)
	item.Outcome, item.Message = OutcomeRestored, msgCreated
	return applied{item: item, after: a.smartCollectionCreated(c.CollectionType, newID)}, nil
}

// smartCollectionCreated is the after-commit refresh of a smart collection
// the restore created (RestoreTargets.SmartCollectionCreated), or nil. The
// count is derived; a failed refresh waits for the periodic one.
func (a *applier) smartCollectionCreated(collectionType, id string) func(context.Context) {
	refresh := a.s.targets.SmartCollectionCreated
	if refresh == nil || collectionType != collectionTypeSmart {
		return nil
	}
	return func(ctx context.Context) {
		if err := refresh(ctx, id); err != nil {
			slog.WarnContext(ctx, "refreshing a restored smart collection's count failed", "component", "backup", "collection_id", id, "error", err)
		}
	}
}

// collectionTypeSmart is a collection whose items its rules choose.
const collectionTypeSmart = "smart"

// collectionRestoredMessage says what restoring onto a collection here
// did: the items it added and the groups it put the collection back in,
// each only when there were any.
func collectionRestoredMessage(added, grouped int) string {
	switch {
	case grouped == 0:
		return fmt.Sprintf("Added %s to the collection here.", counted(added, "item", "items"))
	case added == 0:
		return fmt.Sprintf("Put the collection here back in %s.", counted(grouped, "group", "groups"))
	}
	return fmt.Sprintf("Added %s to the collection here and put it back in %s.", counted(added, "item", "items"), counted(grouped, "group", "groups"))
}

// restoreOntoCollection adds the items a collection here lacks and puts its
// memberships back in their groups. The collection's parent is locked
// first, before anything that can take a library's order revision (a
// group created, items added, a membership regrouped), as the library
// editor locks.
func (a *applier) restoreOntoCollection(ctx context.Context, tx pgx.Tx, id string, plan collectionPlan, c CollectionEntry, libMap map[int]int, item ReportItem) (applied, error) {
	if err := catalog.LockLibraryCollectionInTx(ctx, tx, plan.localID); err != nil {
		return applied{}, err
	}
	added, err := catalog.AddMissingItemsInTx(ctx, tx, plan.localID, plan.missing)
	if err != nil {
		return applied{}, err
	}
	grouped, err := restoreGroups(ctx, tx, plan.localID, c, libMap)
	if err != nil {
		return applied{}, err
	}
	a.claim(claimCollection, plan.localID, id)
	if len(added) == 0 && grouped == 0 {
		return unchanged(item), nil
	}
	item.Outcome = OutcomeRestored
	item.Message = collectionRestoredMessage(len(added), grouped)
	return applied{item: item}, nil
}

// createCollection creates every collection a restore creates, by input,
// under the rules all of them follow. Its source is stored in the editors'
// canonical form. When input's source and sync
// schedule are the backup's (fromBackup) and the backup is one this server
// cannot verify, the collection keeps its source but gets no sync
// schedule, so it fetches nothing until an admin schedules or syncs it,
// and notes say so. A template collection's come from this server's
// template (the backup's changes to them are withheld, customizeTemplate).
func (a *applier) createCollection(ctx context.Context, tx pgx.Tx, input catalog.CreateLibraryCollectionInput, fromBackup bool, notes *[]string) error {
	// The source is stored as the editors store one; the plan refused one
	// that does not canonicalize (planner.checkCollection).
	var err error
	if input.SourceURL, input.SourceConfig, err = collectionutil.CanonicalCollectionSource(input.CollectionType, input.SourceURL, input.SourceConfig); err != nil {
		return err
	}
	if fromBackup && a.rs.unverified && scheduleOf(input.SyncSchedule) != "" {
		input.SyncSchedule = nil
		*notes = append(*notes, msgScheduleWithheld)
	}
	_, err = catalog.CreateLibraryCollectionInTx(ctx, tx, input)
	return err
}

// msgScheduleWithheld reports a collection restored without its schedule.
const msgScheduleWithheld = "Created without its sync schedule: it is not restored from a backup this server cannot verify."

// scheduleNote is the preview's word on a collection with schedule that a
// restore creates (what, as the sentence's subject): from a backup this
// server cannot verify, it gets no schedule.
func (p *planner) scheduleNote(what string, schedule *string) string {
	if p.authenticated || scheduleOf(schedule) == "" {
		return ""
	}
	return what + " no sync schedule: a backup this server cannot verify does not make a collection fetch from outside services on a schedule."
}

// mapIn turns a library map into the lookup userdata takes.
func mapIn(m map[int]int) func(int) (int, bool) {
	return func(id int) (int, bool) {
		local, ok := m[id]
		return local, ok
	}
}

func thumbFor(key, thumb string) string {
	if key == "" || !validThumbhash(thumb) {
		return ""
	}
	return thumb
}

// copyCollectionArt copies a collection's uploaded image, with its stored
// variants, from collection-images/<old id>/ to the same path under the new
// id. Any other reference (provider artwork) is kept as it is.
func (a *applier) copyCollectionArt(ctx context.Context, oldID, newID, key string, item *ReportItem) (string, error) {
	oldPrefix := "collection-images/" + oldID + "/"
	if !strings.HasPrefix(key, "collection-images/") {
		return key, nil
	}
	if !strings.HasPrefix(key, oldPrefix) || !a.rs.HasBlob(key) {
		item.MissingBlobs = append(item.MissingBlobs, key)
		item.Notes = append(item.Notes, "An image of the collection was missing from the backup.")
		return "", nil
	}
	newPrefix := "collection-images/" + newID + "/"
	for _, from := range a.rs.blobFamily(key) {
		if !strings.HasPrefix(from, oldPrefix) {
			continue
		}
		if err := a.writeBlob(ctx, from, newPrefix+strings.TrimPrefix(from, oldPrefix)); err != nil {
			return "", err
		}
	}
	return newPrefix + strings.TrimPrefix(key, oldPrefix), nil
}

// restoreGroups puts each of the collection's memberships here into the
// group its backup membership had, through the mapped library: the group of
// the same slug in that library, created when missing. Only ungrouped
// memberships change, so a group an admin chose since stays. It returns how
// many memberships it grouped.
func restoreGroups(ctx context.Context, tx pgx.Tx, collectionID string, c CollectionEntry, libMap map[int]int) (int, error) {
	grouped := 0
	for _, lib := range c.Libraries {
		local, ok := libMap[lib.LibraryID]
		if !ok || lib.GroupSlug == "" {
			continue
		}
		groupID, err := groupFor(ctx, tx, lib, local)
		if err != nil {
			return grouped, err
		}
		changed, err := catalog.GroupUngroupedMembershipInTx(ctx, tx, collectionID, local, groupID)
		if err != nil {
			return grouped, err
		}
		if changed {
			grouped++
		}
	}
	return grouped, nil
}

// groupFor finds the regular group of the backup membership's slug in a
// library here, creating it when missing.
func groupFor(ctx context.Context, tx pgx.Tx, lib CollectionLib, libraryID int) (string, error) {
	var id string
	err := tx.QueryRow(ctx, `SELECT id FROM library_collection_groups WHERE library_id = $1 AND slug = $2 AND kind = 'regular'`, libraryID, lib.GroupSlug).Scan(&id)
	if err == nil {
		return id, nil
	}
	if !errors.Is(err, pgx.ErrNoRows) {
		return "", err
	}
	name := lib.GroupName
	if name == "" {
		name = lib.GroupSlug
	}
	group, err := catalog.CreateLibraryCollectionGroupInTx(ctx, tx, catalog.CreateLibraryCollectionGroupInput{
		LibraryID: libraryID, Name: name, Slug: lib.GroupSlug, DefaultSortMode: models.GroupSortMode(groupSortMode(lib.GroupSort)),
	})
	if err != nil {
		return "", fmt.Errorf("creating the collection group: %w", err)
	}
	return group.ID, nil
}

// freeSlug keeps the backup's slug unless another collection of the library
// has it.
func freeSlug(ctx context.Context, tx pgx.Tx, libraryID int, slug string) (string, error) {
	candidate := slug
	for n := 2; n < 1000; n++ {
		var taken bool
		if err := tx.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM library_collections WHERE library_id = $1 AND slug = $2)`, libraryID, candidate).Scan(&taken); err != nil {
			return "", err
		}
		if !taken {
			return candidate, nil
		}
		candidate = fmt.Sprintf("%s-%d", slug, n)
	}
	return "", fmt.Errorf("no free slug for %q", slug)
}

// groupSortMode keeps a known group sort mode and falls back to manual.
func groupSortMode(mode string) string {
	switch mode {
	case "manual", "name_asc", "name_desc", "recent", "most_items":
		return mode
	}
	return "manual"
}

// Budgets for the collection metadata (everything but item lists) one
// restore writes, in all and into one library: an entry may hold up to
// maxRestoredEntryBytes, and a library's collections are listed whole.
const (
	maxRestoreCollectionMetadata = 16 << 20
	maxLibraryCollectionMetadata = 8 << 20
)

// collectionCharge is the collection metadata one item writes into one
// library here.
type collectionCharge struct {
	library int
	bytes   int64
}

// collectionCost is the encoded size of a collection entry without its
// item list.
func collectionCost(v any) int64 {
	if c, ok := v.(CollectionEntry); ok {
		c.Items = nil
		v = c
	}
	data, err := json.Marshal(v)
	if err != nil {
		return maxRestoreCollectionMetadata
	}
	return int64(len(data))
}

// overCollectionBudget leaves an item out when its metadata would take the
// restore, or its library, past the collection metadata budget.
func (a *applier) overCollectionBudget(item ReportItem, c collectionCharge) (applied, bool) {
	if a.collectionBytes+c.bytes <= maxRestoreCollectionMetadata && a.libraryCollectionBytes[c.library]+c.bytes <= maxLibraryCollectionMetadata {
		return applied{}, false
	}
	return leftOut(item, ReasonOverRestoreBudget, "This restore already wrote as much collection metadata as one restore may, in all or into its library. Restore it on its own."), true
}

// charge adds a committed item's collection metadata to the budget.
func (a *applier) charge(c collectionCharge) {
	if c.bytes == 0 {
		return
	}
	if a.libraryCollectionBytes == nil {
		a.libraryCollectionBytes = map[int]int64{}
	}
	a.collectionBytes += c.bytes
	a.libraryCollectionBytes[c.library] += c.bytes
}

// withCollectionBudget runs write for a template collection or a section
// that carries a collection, charging its collection metadata as
// applyCollection does; anything else runs as it is.
func (a *applier) withCollectionBudget(id string, write func(context.Context, pgx.Tx, string) (applied, error)) func(context.Context, pgx.Tx) (applied, error) {
	return func(ctx context.Context, tx pgx.Tx) (applied, error) {
		var charge collectionCharge
		item := ReportItem{Label: id}
		libMap := a.libraryMap()
		if t := indexed(a.rs.Collections.TemplateCollections, a.rs.lookup().templates, id); t != nil {
			item.Kind, item.Label = KindTemplateCollection, t.Title
			charge = collectionCharge{library: libMap[t.LibraryID], bytes: collectionCost(*t)}
		} else if e := indexed(a.rs.HomeSections.Sections, a.rs.lookup().sections, id); e != nil && e.Collection != nil {
			item.Kind, item.Label = KindHomeSection, e.Title
			charge = collectionCharge{library: libMap[e.Collection.LibraryID], bytes: collectionCost(e.Collection.CollectionEntry)}
		}
		if charge.bytes > 0 {
			if over, ok := a.overCollectionBudget(item, charge); ok {
				return over, nil
			}
		}
		result, err := write(ctx, tx, id)
		if result.item.Outcome == OutcomeRestored {
			result.metadata = charge
		}
		return result, err
	}
}
