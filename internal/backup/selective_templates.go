package backup

// Template-bundle collections: which template was applied to which library,
// and what the admin changed since. A missing one is created from this
// server's template, the way a bundle apply creates it, then synced; an
// existing one only takes the admin's changes that differ.

import (
	"bytes"
	"cmp"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"strconv"
	"strings"

	"github.com/jackc/pgx/v5"

	"github.com/Silo-Server/silo-server/internal/backup/userdata"
	"github.com/Silo-Server/silo-server/internal/catalog"
	"github.com/Silo-Server/silo-server/internal/idgen"
)

// templatePlan is one template collection against this server.
type templatePlan struct {
	item     PreviewItem
	library  int
	defaults TemplateDefaults
	// local is the collection here with the remapped management key.
	local *localTemplateCollection
	// custom is what the restore writes: the backup's changes from the
	// template's defaults that this server's collection lacks.
	custom templateCustomization
	// groups is how many memberships here go back into their group.
	groups int
}

// localTemplateCollection is the fields a customization compares.
type localTemplateCollection struct {
	id                                      string
	title, description, visibility          string
	featured                                bool
	sortOrder                               int
	sortConfig, sourceConfig                json.RawMessage
	sourceURL                               string
	syncSchedule                            *string
	poster, backdrop                        string
	posterAutoGenerated, posterFromTemplate bool
}

// templateCustomization is the update a restore writes, the fields it
// names for display, and the images it copies.
type templateCustomization struct {
	changes          []string
	update           catalog.UpdateLibraryCollectionInput
	poster, backdrop string
}

func (c templateCustomization) empty() bool { return len(c.changes) == 0 }

// templateLabel is "<template title> in <library>": the template's title in
// this server's catalog, else the backup's.
func (p *planner) templateLabel(t TemplateCollectionEntry) string {
	title := t.Title
	if p.s.targets.TemplateTitle != nil {
		if name, ok := p.s.targets.TemplateTitle(t.TemplateID); ok && name != "" {
			title = name
		}
	}
	for _, l := range p.rs.Libraries.Libraries {
		if l.ID == t.LibraryID {
			return title + " in " + l.Name
		}
	}
	return title
}

func (p *planner) planTemplateCollection(ctx context.Context, t TemplateCollectionEntry, libMap map[int]int, restorable map[int]bool) (templatePlan, error) {
	plan := templatePlan{item: PreviewItem{ID: t.itemID(), Kind: KindTemplateCollection, Label: p.templateLabel(t),
		Collection: &PreviewCollected{TemplateID: t.TemplateID, BundleID: t.BundleID}}}
	for _, key := range []string{t.Poster, t.Backdrop} {
		if strings.HasPrefix(key, "collection-images/") && !p.rs.HasBlob(key) {
			plan.item.MissingBlobs = append(plan.item.MissingBlobs, key)
		}
	}
	notAvailable := func(message string) (templatePlan, error) {
		plan.item.Status, plan.item.Reason, plan.item.Message = ItemNotOnThisServer, ReasonTemplateNotAvailable, message
		return plan, nil
	}
	if p.s.targets.TemplateCollection == nil || p.s.targets.TemplateTitle == nil {
		return notAvailable("This server cannot create collections from templates.")
	}
	if _, ok := p.s.targets.TemplateTitle(t.TemplateID); !ok {
		return notAvailable(fmt.Sprintf("This server's collection templates do not include %q.", t.TemplateID))
	}
	local, ok := libMap[t.LibraryID]
	if !ok {
		if restorable[t.LibraryID] {
			plan.item.Status, plan.item.Selectable = ItemNotOnThisServer, true
			plan.item.Requires = []string{libraryRef(t.LibraryID)}
			plan.item.Message = "Created from its template with its library, then synced."
			return plan, nil
		}
		plan.item.Status, plan.item.Reason = ItemNotOnThisServer, ReasonLibraryNotRestorable
		plan.item.Message = "Its library is not on this server and cannot be restored."
		return plan, nil
	}
	plan.library = local
	plan.item.Collection.LibraryIDs = []int{local}
	// Two of the backup's libraries that became one here would give two of
	// its collections one management key.
	if twins := p.templateTwins(t, local, libMap); twins > 1 {
		plan.item.Status, plan.item.Reason = ItemAmbiguous, ReasonAmbiguousName
		plan.item.Message = fmt.Sprintf("%d collections of the backup come from this template for this library here.", twins)
		return plan, nil
	}
	var libraryType string
	if err := p.q.QueryRow(ctx, `SELECT type FROM media_folders WHERE id = $1`, local).Scan(&libraryType); err != nil {
		return plan, fmt.Errorf("reading library %d: %w", local, err)
	}
	defaults, err := p.s.targets.TemplateCollection(t.BundleID, t.TemplateID, local, libraryType)
	if errors.Is(err, ErrTemplateNotAvailable) {
		return notAvailable("This server's template does not suit the library here.")
	}
	if err != nil {
		return plan, err
	}
	plan.defaults = defaults
	if plan.local, err = readTemplateCollection(ctx, p.q, t.BundleID, TemplateManagementKey(t.BundleID, t.TemplateID, local)); err != nil {
		return plan, err
	}
	asCollection := CollectionEntry{ID: t.ID, LibraryID: t.LibraryID, Libraries: t.Libraries}
	if plan.local == nil {
		plan.custom = customizeTemplate(t, defaults.Input, nil, libMap)
		plan.item.Status, plan.item.Selectable = ItemNotOnThisServer, true
		plan.item.Message = "Created from its template, then synced."
		if !plan.custom.empty() {
			plan.item.Message = "Created from its template with the changes made to it (" + strings.Join(plan.custom.changes, ", ") + "), then synced."
		}
		plan.item.Collection.Changes = plan.custom.changes
		return plan, nil
	}
	plan.item.Collection.LocalID = plan.local.id
	plan.custom = customizeTemplate(t, defaults.Input, plan.local, libMap)
	if plan.groups, err = ungroupedMemberships(ctx, p.q, plan.local.id, asCollection, libMap); err != nil {
		return plan, err
	}
	plan.item.Collection.Changes = plan.custom.changes
	if plan.custom.empty() && plan.groups == 0 {
		plan.item.Status, plan.item.Reason = ItemOnThisServer, ReasonSame
		return plan, nil
	}
	plan.item.Status, plan.item.Selectable = ItemDiffers, true
	var parts []string
	if !plan.custom.empty() {
		parts = append(parts, "applies the changes made to it ("+strings.Join(plan.custom.changes, ", ")+")")
	}
	if plan.groups > 0 {
		parts = append(parts, fmt.Sprintf("puts it back in %d groups", plan.groups))
	}
	plan.item.Message = "The collection here " + strings.Join(parts, " and ") + "."
	return plan, nil
}

// readTemplateCollection reads the collection here with a template bundle's
// management key, or nil.
func readTemplateCollection(ctx context.Context, q queryer, bundleID, key string) (*localTemplateCollection, error) {
	var c localTemplateCollection
	var sortConfig, sourceConfig string
	err := q.QueryRow(ctx, `
		SELECT id, title, description, visibility, featured, sort_order, sort_config::text, source_config::text, source_url, sync_schedule,
			poster_url, backdrop_url, poster_auto_generated, poster_from_template
		FROM library_collections WHERE management_mode = 'template_bundle' AND management_source = $1 AND management_key = $2`, bundleID, key).
		Scan(&c.id, &c.title, &c.description, &c.visibility, &c.featured, &c.sortOrder, &sortConfig, &sourceConfig, &c.sourceURL, &c.syncSchedule,
			&c.poster, &c.backdrop, &c.posterAutoGenerated, &c.posterFromTemplate)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading template collections: %w", err)
	}
	c.sortConfig, c.sourceConfig = json.RawMessage(sortConfig), json.RawMessage(sourceConfig)
	return &c, nil
}

// customizeTemplate is what restoring t writes. A field counts as the
// admin's change only where the backup differs from the template's default
// here; it is written only where this server's collection (local, or the
// defaults when it is missing) differs from the backup. A source whose
// libraries are not all here is left as it is.
func customizeTemplate(t TemplateCollectionEntry, def catalog.CreateLibraryCollectionInput, local *localTemplateCollection, libMap map[int]int) templateCustomization {
	defVisibility := cmp.Or(def.Visibility, catalog.LibraryCollectionVisibilityVisible)
	if local == nil {
		local = &localTemplateCollection{title: def.Title, description: def.Description, visibility: defVisibility,
			featured: def.Featured, sortOrder: def.SortOrder, sortConfig: def.SortConfig, sourceConfig: def.SourceConfig, sourceURL: def.SourceURL,
			syncSchedule: def.SyncSchedule, poster: def.PosterURL, posterFromTemplate: def.PosterFromTemplate}
	}
	var c templateCustomization
	u := &c.update
	if t.Title != def.Title && t.Title != local.title {
		u.Title, c.changes = &t.Title, append(c.changes, "title")
	}
	if t.Description != def.Description && t.Description != local.description {
		u.Description, c.changes = &t.Description, append(c.changes, "description")
	}
	if t.Visibility != "" && t.Visibility != defVisibility && t.Visibility != local.visibility {
		u.Visibility, c.changes = &t.Visibility, append(c.changes, "visibility")
	}
	if t.Featured != def.Featured && t.Featured != local.featured {
		u.Featured, c.changes = &t.Featured, append(c.changes, "featured")
	}
	if t.SortOrder != def.SortOrder && t.SortOrder != local.sortOrder {
		u.SortOrder, c.changes = &t.SortOrder, append(c.changes, "sort order")
	}
	if !jsonEqual(t.SortConfig, def.SortConfig) && !jsonEqual(t.SortConfig, local.sortConfig) {
		u.SortConfig, c.changes = t.SortConfig, append(c.changes, "item sort")
	}
	if source, ok := userdata.RemapQueryLibraries(t.SourceConfig, mapIn(libMap)); ok &&
		!jsonEqual(source, def.SourceConfig) && !jsonEqual(source, local.sourceConfig) {
		url := t.SourceURL
		u.SourceConfig, u.SourceURL, c.changes = source, &url, append(c.changes, "source")
	}
	if schedule := scheduleOf(t.SyncSchedule); schedule != scheduleOf(def.SyncSchedule) && schedule != scheduleOf(local.syncSchedule) {
		u.SyncSchedule, c.changes = &schedule, append(c.changes, "sync schedule")
	}
	// An image the admin set: an upload travels as a blob, a URL as is.
	if t.Poster != "" && !t.PosterFromTemplate && !t.PosterAutoGenerated && !sameImage(t.ID, t.Poster, local.id, local.poster) {
		c.poster, c.changes = t.Poster, append(c.changes, "poster")
	}
	if t.Backdrop != "" && !sameImage(t.ID, t.Backdrop, local.id, local.backdrop) {
		c.backdrop, c.changes = t.Backdrop, append(c.changes, "backdrop")
	}
	return c
}

// sameImage reports whether the image here is the backup's: the same URL,
// or the same upload under this collection's id.
func sameImage(backupID, key, localID, local string) bool {
	if key == local {
		return true
	}
	old := "collection-images/" + backupID + "/"
	return localID != "" && strings.HasPrefix(key, old) && local == "collection-images/"+localID+"/"+strings.TrimPrefix(key, old)
}

func scheduleOf(s *string) string {
	if s == nil {
		return ""
	}
	return strings.TrimSpace(*s)
}

// jsonEqual compares two JSON documents by value; empty reads as {}.
func jsonEqual(a, b json.RawMessage) bool {
	norm := func(raw json.RawMessage) string {
		if len(bytes.TrimSpace(raw)) == 0 {
			return "{}"
		}
		var v any
		if json.Unmarshal(raw, &v) != nil {
			return string(raw)
		}
		out, err := json.Marshal(v)
		if err != nil {
			return string(raw)
		}
		return string(out)
	}
	return norm(a) == norm(b)
}

func (a *applier) applyTemplateCollection(ctx context.Context, tx pgx.Tx, id string) (applied, error) {
	item := ReportItem{Kind: KindTemplateCollection, Label: id}
	var t *TemplateCollectionEntry
	for i := range a.rs.Collections.TemplateCollections {
		if a.rs.Collections.TemplateCollections[i].itemID() == id {
			t = &a.rs.Collections.TemplateCollections[i]
		}
	}
	if t == nil {
		return leftOut(item, ReasonNotInBackup, "The backup has no such collection."), nil
	}
	libMap := a.libraryMap()
	p := a.s.newPlanner(a.rs, tx)
	item.Label = p.templateLabel(*t)
	plan, err := p.planTemplateCollection(ctx, *t, libMap, nil)
	if err != nil {
		return applied{}, err
	}
	if plan.item.Reason == ReasonLibraryNotRestorable {
		return leftOut(item, ReasonLibraryNotMapped, "Its library is not on this server."), nil
	}
	if !plan.item.Selectable {
		return leftOutFor(item, plan.item), nil
	}
	asCollection := CollectionEntry{ID: t.ID, LibraryID: t.LibraryID, Libraries: t.Libraries}
	if plan.local != nil {
		return a.updateTemplateCollection(ctx, tx, *t, plan, asCollection, libMap, item)
	}

	newID, err := idgen.NextID()
	if err != nil {
		return applied{}, err
	}
	numericID, err := strconv.Atoi(newID)
	if err != nil {
		return applied{}, fmt.Errorf("collection id %q is not numeric: %w", newID, err)
	}
	input := plan.defaults.Input
	input.ID = newID
	if input.Slug, err = freeSlug(ctx, tx, plan.library, input.Slug); err != nil {
		return applied{}, err
	}
	applyCustomization(&input, plan.custom.update)
	var images catalog.UpdateLibraryCollectionInput
	if err := a.templateImages(ctx, *t, newID, plan.custom, &images, &item); err != nil {
		return applied{}, err
	}
	if images.PosterURL != nil {
		input.PosterURL, input.PosterThumbhash, input.PosterAutoGenerated, input.PosterFromTemplate = *images.PosterURL, *images.PosterThumbhash, false, false
	}
	if images.BackdropURL != nil {
		input.BackdropURL, input.BackdropThumbhash = *images.BackdropURL, *images.BackdropThumbhash
	}
	if _, err := catalog.CreateLibraryCollectionInTx(ctx, tx, input); err != nil {
		return applied{}, err
	}
	if _, err := restoreGroups(ctx, tx, newID, asCollection, libMap); err != nil {
		return applied{}, err
	}
	// The template poster and the first sync run after commit, as a bundle
	// apply runs them after creating; the row keeps them owed until done.
	if err := recordFollowUp(ctx, tx, followUpCollectionCreated, numericID); err != nil {
		return applied{}, err
	}
	item.Outcome, item.Message = OutcomeRestored, "Created from its template; it syncs after the restore."
	if plan.defaults.NeedsSetup {
		item.Notes = append(item.Notes, "Its template needs a source set before it can sync.")
	}
	return applied{item: item, after: a.s.CompleteFollowUps}, nil
}

// updateTemplateCollection writes the backup's changes that differ onto the
// collection here and puts it back in its groups.
func (a *applier) updateTemplateCollection(ctx context.Context, tx pgx.Tx, t TemplateCollectionEntry, plan templatePlan, asCollection CollectionEntry, libMap map[int]int, item ReportItem) (applied, error) {
	u := plan.custom.update
	u.ID = plan.local.id
	if err := a.templateImages(ctx, t, plan.local.id, plan.custom, &u, &item); err != nil {
		return applied{}, err
	}
	if err := catalog.UpdateLibraryCollectionColumnsInTx(ctx, tx, u); err != nil {
		return applied{}, err
	}
	grouped, err := restoreGroups(ctx, tx, plan.local.id, asCollection, libMap)
	if err != nil {
		return applied{}, err
	}
	if plan.custom.empty() && grouped == 0 {
		return unchanged(item), nil
	}
	item.Outcome, item.Message = OutcomeRestored, plan.item.Message
	return applied{item: item}, nil
}

// applyCustomization writes a customization's column fields onto a create.
func applyCustomization(in *catalog.CreateLibraryCollectionInput, u catalog.UpdateLibraryCollectionInput) {
	if u.Title != nil {
		in.Title = *u.Title
	}
	if u.Description != nil {
		in.Description = *u.Description
	}
	if u.Visibility != nil {
		in.Visibility = *u.Visibility
	}
	if u.Featured != nil {
		in.Featured = *u.Featured
	}
	if u.SortOrder != nil {
		in.SortOrder = *u.SortOrder
	}
	if u.SortConfig != nil {
		in.SortConfig = u.SortConfig
	}
	if u.SourceConfig != nil {
		in.SourceConfig = u.SourceConfig
	}
	if u.SourceURL != nil {
		in.SourceURL = *u.SourceURL
	}
	if u.SyncSchedule != nil {
		in.SyncSchedule = nil
		if *u.SyncSchedule != "" {
			schedule := *u.SyncSchedule
			in.SyncSchedule = &schedule
		}
	}
}

// templateImages copies the admin's uploaded images under the collection
// here and sets them on u; a URL is set as it is.
func (a *applier) templateImages(ctx context.Context, t TemplateCollectionEntry, localID string, c templateCustomization, u *catalog.UpdateLibraryCollectionInput, item *ReportItem) error {
	if c.poster != "" {
		key, err := a.copyCollectionArt(ctx, t.ID, localID, c.poster, item)
		if err != nil {
			return err
		}
		if key != "" {
			thumb, notAuto, notTemplate := thumbFor(key, t.PosterThumbhash), false, false
			u.PosterURL, u.PosterThumbhash, u.PosterAutoGenerated, u.PosterFromTemplate = &key, &thumb, &notAuto, &notTemplate
		}
	}
	if c.backdrop != "" {
		key, err := a.copyCollectionArt(ctx, t.ID, localID, c.backdrop, item)
		if err != nil {
			return err
		}
		if key != "" {
			thumb := thumbFor(key, t.BackdropThumbhash)
			u.BackdropURL, u.BackdropThumbhash = &key, &thumb
		}
	}
	return nil
}
