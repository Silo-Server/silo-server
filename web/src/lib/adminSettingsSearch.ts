/*
 * Text in this registry (and in lib/adminNavigation) is stored as message ids
 * and read through getters: `item.label`, `item.description`, `item.keywords`
 * and each `settings[i].label` call `t()` when they are read, so they are always
 * in the current interface language. Consumers keep reading plain strings; a
 * component that shows them calls `useT()` or `useAppLanguage()` so it
 * re-renders on a language change. Copying an item with `{ ...item }` or
 * `Object.assign` reads the getters once and freezes that language's text, so
 * keep a reference to the item instead.
 *
 * Keywords are English search synonyms and are never shown. In a translated
 * interface `keywords` (and each setting entry's `keywords`) also carry the
 * English label and description, so an English query finds what it found
 * before while the translated label and description match translated queries.
 * In English they are exactly the hand-written keywords.
 */
