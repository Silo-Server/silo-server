export interface AdminSettingsSearchItem extends SettingsSearchItem {
  id: string;
  /** In the current interface language (a getter; see the top of this file). */
  label: string;
  /** In the current interface language (a getter; see the top of this file). */
  description: string;
  keywords?: readonly string[];
  /**
   * Every group heading and control on the page, by its visible label, so the
   * sidebar search and ⌘K can find it. Keep it in step with the page.
   */
  settings?: readonly SettingsSearchEntry[];
  icon: LucideIcon;
  /**
   * Short qualifier rendered next to the label in a nav that wants one. The
   * admin sidebar reads page health as a status dot instead, so nothing sets
   * this today; the prop stays so a future nav can opt in without reshaping
   * the item type.
   */
  badge?: string;
}

/**
 * The English text of `ids`, as extra search terms, when the interface is in
 * another language; nothing in English, where the shown text already is
 * English. Keeps English queries working in a translated interface.
 */
export function englishSearchTerms(...ids: readonly MessageKey[]): string[] {
  if (appIntl().locale === "en") return [];
  return ids.map((id) => englishText(id));
}

/**
 * A search index entry: a label in the interface language, searchable in
 * English too. In English it has no keywords, as before translation.
 */
export function searchEntry(labelKey: MessageKey): SettingsSearchEntry {
  return {
    get label() {
      return t(labelKey);
    },
    get keywords() {
      const english = englishSearchTerms(labelKey);
      return english.length > 0 ? english : undefined;
    },
  };
}

interface SettingsPageDefinition {
  id: string;
  labelKey: MessageKey;
  descriptionKey: MessageKey;
  keywords?: readonly string[];
  /** Every group heading and control on the page (see `AdminSettingsSearchItem.settings`). */
  settings?: readonly MessageKey[];
  icon: LucideIcon;
}

function settingsPage(page: SettingsPageDefinition): AdminSettingsSearchItem {
  return {
    id: page.id,
    get label() {
      return t(page.labelKey);
    },
    get description() {
      return t(page.descriptionKey);
    },
    get keywords() {
      return [...(page.keywords ?? []), ...englishSearchTerms(page.labelKey, page.descriptionKey)];
    },
    settings: page.settings?.map(searchEntry),
    icon: page.icon,
  };
}

