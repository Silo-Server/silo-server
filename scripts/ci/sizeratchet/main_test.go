func gitTest(t *testing.T, args ...string) string {
	t.Helper()
	// Keep background writers out of fixtures, including the checker's Git calls.
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_PARAMETERS", "")
	t.Setenv("GIT_CONFIG_COUNT", "3")
	t.Setenv("GIT_CONFIG_KEY_0", "maintenance.auto")
	t.Setenv("GIT_CONFIG_VALUE_0", "false")
	t.Setenv("GIT_CONFIG_KEY_1", "gc.auto")
	t.Setenv("GIT_CONFIG_VALUE_1", "0")
	t.Setenv("GIT_CONFIG_KEY_2", "core.fsmonitor")
	t.Setenv("GIT_CONFIG_VALUE_2", "false")
	cmd := exec.CommandContext(context.Background(), "git", args...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v: %s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func writeTest(t *testing.T, file, text string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(file), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(file, []byte(text), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestGitDoesNotStartMaintenance(t *testing.T) {
	t.Chdir(t.TempDir())
	// Keep injected maintenance synchronous so a regression cannot race cleanup.
	t.Setenv("GIT_CONFIG_COUNT", "1")
	t.Setenv("GIT_CONFIG_KEY_0", "maintenance.autoDetach")
	t.Setenv("GIT_CONFIG_VALUE_0", "false")
	t.Setenv("GIT_CONFIG_PARAMETERS", "'maintenance.auto=true'")
	t.Setenv("GIT_TRACE", "1")
	gitTest(t, "init", "-q")
	writeTest(t, "README", "fixture\n")
	gitTest(t, "add", ".")
	out := gitTest(t, "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-qm", "base")
	if strings.Contains(out, "maintenance run") || strings.Contains(out, "gc --auto") {
		t.Fatalf("git commit started maintenance; want no maintenance subprocess:\n%s", out)
	}
}

func TestFileCrossings(t *testing.T) {
	for _, tc := range []struct {
		name, file    string
		before, after int
		tracked, fail bool
	}{
		{"Go exact", "a.go", 999, 1000, true, false},
		{"Go crossing", "a.go", 1000, 1001, true, true},
		{"test exact", "a_test.go", 1999, 2000, true, false},
		{"test crossing", "a_test.go", 2000, 2001, true, true},
		{"TS exact", "a.ts", 799, 800, true, false},
		{"TS crossing", "a.ts", 800, 801, true, true},
		{"TSX crossing", "a.tsx", 800, 801, true, true},
		{"unchanged debt", "a.go", 1001, 1001, true, false},
		{"growing debt", "a.go", 1001, 1002, true, false},
		{"shrinking debt", "a.go", 1002, 1001, true, false},
		{"new exact", "a.go", 0, 1000, false, false},
		{"new over", "a.go", 0, 1001, false, true},
		{"other file", "a.md", 1000, 1001, true, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Chdir(t.TempDir())
			gitTest(t, "init", "-q")
			writeTest(t, "README", "fixture\n")
			if tc.tracked {
				writeTest(t, tc.file, strings.Repeat("// base\n", tc.before))
			}
			gitTest(t, "add", ".")
			gitTest(t, "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-qm", "base")
			base := gitTest(t, "rev-parse", "HEAD")
			writeTest(t, tc.file, strings.Repeat("// head\n", tc.after))
			err := run([]string{"-base", base})
			if (err != nil) != tc.fail {
				t.Fatalf("run = %v; want failure %t", err, tc.fail)
			}
			if tc.fail && !strings.Contains(err.Error(), tc.file) {
				t.Fatalf("run = %v; want file %s", err, tc.file)
			}
		})
	}
}

func TestRenameDeletionAndGenerated(t *testing.T) {
	t.Chdir(t.TempDir())
	gitTest(t, "init", "-q")
	writeTest(t, "old.go", strings.Repeat("// base\n", 1001))
	writeTest(t, "deleted.go", strings.Repeat("// base\n", 1001))
	gitTest(t, "add", ".")
	gitTest(t, "-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-qm", "base")
	base := gitTest(t, "rev-parse", "HEAD")
	gitTest(t, "mv", "old.go", "new.go")
	gitTest(t, "rm", "deleted.go")
	writeTest(t, "new.go", strings.Repeat("// base\n", 1002))
	writeTest(t, "generated.go", "// Code generated by fixture. DO NOT EDIT.\n"+strings.Repeat("// generated\n", 1001))
	writeTest(t, "settingsContract.ts", "/**\n * Code generated by cmd/settingsgen from contracts/settings/v1/manifest.json. DO NOT EDIT.\n */\n"+strings.Repeat("// generated\n", 801))
	writeTest(t, "operations.ts", "/**\n * This file was auto-generated by scripts/generate-apiv2.mjs from\n * contracts/api/v2/openapi.json. Do not make direct changes to the file.\n */\n"+strings.Repeat("// generated\n", 801))
	if err := run([]string{"-base", base}); err != nil {
		t.Fatalf("rename/deletion/generated: %v; want success", err)
	}
	if err := run([]string{"-base", "missing-base"}); err == nil {
		t.Fatal("missing base accepted; want error")
	}
}

func TestLines(t *testing.T) {
	for _, tc := range []struct {
		text string
		want int
	}{{"", 0}, {"a", 1}, {"a\n", 1}, {"a\nb", 2}} {
		if got := lines([]byte(tc.text)); got != tc.want {
			t.Errorf("lines(%q) = %d, want %d", tc.text, got, tc.want)
		}
	}
}
