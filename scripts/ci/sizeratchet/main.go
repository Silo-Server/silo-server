// Command sizeratchet rejects files that cross their line limit since the base.
package main

import (
	"bytes"
	"context"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

func lines(data []byte) int {
	n := bytes.Count(data, []byte{'\n'})
	if len(data) > 0 && data[len(data)-1] != '\n' {
		n++
	}
	return n
}

func generated(data []byte) bool {
	block := false
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		var comment string
		switch {
		case block:
			comment = line
		case strings.HasPrefix(line, "/*"):
			block = true
			comment = strings.TrimPrefix(line, "/*")
		case strings.HasPrefix(line, "//"):
			comment = strings.TrimPrefix(line, "//")
		case line == "":
			continue
		default:
			return false
		}
		end := strings.Index(comment, "*/")
		text := comment
		if block && end >= 0 {
			text = comment[:end]
			block = false
		}
		text = strings.TrimSpace(strings.TrimLeft(text, "*"))
		if (strings.HasPrefix(text, "Code generated ") && strings.HasSuffix(text, " DO NOT EDIT.")) ||
			strings.HasPrefix(text, "This file was auto-generated by scripts/generate-apiv2.mjs from") {
			return true
		}
		if end >= 0 && strings.TrimSpace(comment[end+2:]) != "" {
			return false
		}
	}
	return false
}

func git(args ...string) ([]byte, error) {
	out, err := exec.CommandContext(context.Background(), "git", args...).Output() //nolint:gosec // Git argument lists are constructed by this checker; no shell is invoked.
	if err != nil {
		return nil, fmt.Errorf("git %v: %w", args, err)
	}
	return out, nil
}

func checkFile(base, before, file string) error {
	var limit int
	switch {
	case strings.HasSuffix(file, "_test.go"):
		limit = 2000
	case strings.HasSuffix(file, ".go"):
		limit = 1000
	case strings.HasSuffix(file, ".ts"), strings.HasSuffix(file, ".tsx"):
		limit = 800
	default:
		return nil
	}
	data, err := os.ReadFile(filepath.Clean(file))
	if err != nil {
		return err
	}
	if generated(data) {
		return nil
	}
	var old []byte
	if before != "" {
		old, err = git("show", base+":"+before)
		if err != nil {
			return err
		}
	}
	if lines(old) <= limit && lines(data) > limit {
		return fmt.Errorf("%s: %d -> %d lines crosses limit %d", file, lines(old), lines(data), limit)
	}
	return nil
}

func run(args []string) error {
	flags := flag.NewFlagSet("sizeratchet", flag.ContinueOnError)
	base := flags.String("base", "", "base commit to compare")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if *base == "" {
		return errors.New("-base is required")
	}
	diff, err := git("diff", "--no-ext-diff", "--no-textconv", "--name-status", "-z", "-M", "--diff-filter=AMR", *base, "--")
	if err != nil {
		return err
	}
	records := strings.Split(strings.TrimSuffix(string(diff), "\x00"), "\x00")
	var failures []error
	for i := 0; i < len(records) && records[i] != ""; {
		status, before, file := records[i], records[i+1], records[i+1]
		i += 2
		if status[0] == 'R' {
			file = records[i]
			i++
		}
		if status == "A" {
			before = ""
		}
		if err := checkFile(*base, before, file); err != nil {
			failures = append(failures, err)
		}
	}
	untracked, err := git("ls-files", "--others", "--exclude-standard", "-z")
	if err != nil {
		return err
	}
	for _, file := range strings.Split(string(untracked), "\x00") {
		if file == "" {
			continue
		}
		if err := checkFile(*base, "", file); err != nil {
			failures = append(failures, err)
		}
	}
	return errors.Join(failures...)
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "sizeratchet:", err)
		os.Exit(1)
	}
}
